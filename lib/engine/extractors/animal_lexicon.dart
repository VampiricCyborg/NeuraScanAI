/// The animals the verbal-fluency step accepts, in English and Tamil.
///
/// The step asks the user to name as many animals as they can in thirty seconds, and the
/// measurement is how many valid, different animals they named. Deciding what is valid has to
/// happen on the device and offline (the app has no speech recognition and never sends what a
/// user types anywhere), so it is a list.
///
/// The lists are deliberately everyday: the animals a person of any background would name in
/// thirty seconds, plus common farm, wild, sea, bird and insect animals. They are not meant to
/// be exhaustive and they are not scientific. A user who names a real animal that is missing
/// is under-counted by one, which is the same in every test they take, so it does not move
/// their trend; but the lists are plain data and meant to be extended.
///
/// Words are lower case, one spelling each. Plurals and small typing slips are handled by the
/// extractor, not by listing variants here.
